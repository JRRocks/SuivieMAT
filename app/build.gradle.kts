    namespace = "com.scanlist.app"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.scanlist.app"
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    // Les modeles ML Kit embarques pesent lourd et sont livres pour quatre ABI.
    // Filtrer divise l'APK par ~4, mais un APK arm64 seul refuse de s'installer sur
    // l'emulateur x86_64 : le debug embarque donc les deux architectures.
    buildTypes {
        debug {
            ndk {
                abiFilters += listOf("arm64-v8a", "x86_64")
            }
        }
        release {
            // Materiel cible : Galaxy S25, arm64 uniquement.
            ndk {
                abiFilters += "arm64-v8a"
            }
            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        compose = true
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
}

